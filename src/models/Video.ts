import { Schema, model, Document } from 'mongoose';

// 1. THE ARCHITECTURAL DICTIONARY (The Interface)
// This explicitly teaches TypeScript exactly what data types to expect. 
// It guarantees that a score is ALWAYS a number, a link is ALWAYS a string, etc.
export interface IVideo extends Document {
  platform: 'tiktok' | 'instagram' | 'youtube'; // Must be one of these three exact words
  originId: string;               // The original post ID from TikTok/IG so we never save duplicates
  originCreator: string;          // The handle of the creator, e.g., "tech_hacks_daily"
  rawSourceUrl: string;           // The original volatile link (useful for debugging)
  cdnVideoUrl: string;            // The permanent link to OUR fast AWS cloud storage (never expires)
  cdnThumbnailUrl: string;        // The permanent link to the video's cover image on our cloud
  caption: string;                // The written description of the video
  aiTags: string[];               // An array of descriptive categories generated by our upcoming AI layer
  aiScore: number;                // A quality score from 1-10 ensuring content value
  createdAt: Date;                // The exact timestamp when this video entered our database
}

// 2. THE DIGITAL CONCRETE MOLD (The Schema)
// While the Interface above teaches TypeScript the rules, this Schema teaches 
// our database (MongoDB) exactly how to structure the physical tables and validations.
const VideoSchema = new Schema<IVideo>({
  platform: { type: String, required: true, enum: ['tiktok', 'instagram', 'youtube'] },
  originId: { type: String, required: true, unique: true }, // 'unique: true' stops accidental duplicates
  originCreator: { type: String, required: true },
  rawSourceUrl: { type: String, required: true },
  cdnVideoUrl: { type: String, required: true },
  cdnThumbnailUrl: { type: String, required: true },
  caption: { type: String, required: true },
  aiTags: { type: [String], default: [] }, // Defaults to an empty list if no tags are provided yet
  aiScore: { type: Number, required: true, min: 1, max: 10 }, // Forces our AI to rate it within boundaries
  createdAt: { type: Date, default: Date.now } // Automatically stamps the exact date and time right now
});

// 3. THE WAREHOUSE OPERATOR (The Model)
// This wraps our rules into a live tool named 'Video' that we can use across 
// our backend to create, find, or delete video data records.
export const Video = model<IVideo>('Video', VideoSchema);
